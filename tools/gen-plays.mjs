// Writes tests/native/journey.play: the whole game played from a fresh guest
// profile with the keyboard, every level solved in par from data/levels.json's
// stored optimal solutions (so every level ends with three stars, 180 in
// all), through each world's end card to the final "every maze is painted"
// card. `npm run plays` after regenerating the levels.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const data = JSON.parse(readFileSync(join(root, 'data/levels.json'), 'utf8'));
const KEY = { U: 'ArrowUp', D: 'ArrowDown', L: 'ArrowLeft', R: 'ArrowRight' };
const WORLD = { studio: 'Studio', gallery: 'Gallery', workshop: 'Workshop', atelier: 'Atelier' };
const lines = [
  '# Generated by tools/gen-plays.mjs: all 60 levels solved in par with the arrow keys (desktop), each finish card',
  '# continued with Next level, ending on the last level\'s card with 180 / 180 stars on the title.',
  '# viewport 1280x800@1',
  'until 300 =Play',
  'frames 150',
  'click =Play',
];
data.levels.forEach((lv, i) => {
  const n = i - data.levels.findIndex((l) => l.world === lv.world) + 1;
  lines.push(`until 120 =${WORLD[lv.world]} · ${n}`, 'frames 5');
  for (const d of lv.solution) lines.push(`key ${KEY[d]} 1`, 'frames 1');
  const last = i === data.levels.length - 1;
  const worldEnd = last || data.levels[i + 1].world !== lv.world;
  lines.push(`until 900 ${worldEnd ? `=${WORLD[lv.world]} complete!` : '=Painted!'}`, 'frames 10');
  if (last) {
    lines.push('expect Every maze is painted', 'save journey-end', 'click =Levels #2', 'until 60 ★ 180 / 180', 'frames 10', 'save journey-levels', 'key Escape 1', 'until 60 =Continue', 'expect 180 / 180 stars');
  } else lines.push('click =Next level');
});
writeFileSync(join(root, 'tests/native/journey.play'), lines.join('\n') + '\n');
console.log(`journey.play: ${data.levels.length} levels, ${data.levels.reduce((s, l) => s + l.par, 0)} rolls`);
